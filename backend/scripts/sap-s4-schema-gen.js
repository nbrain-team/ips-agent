#!/usr/bin/env node
/**
 * Generates the sap_s4 column definitions from the S/4HANA views' $metadata.
 *
 *   node scripts/sap-s4-schema-gen.js                 # live (SAP_S4_* env)
 *   node scripts/sap-s4-schema-gen.js --from <dir>    # saved <VIEW>.metadata.xml files
 *   ... --ddl <file.sql>                              # also write CREATE TABLE + COMMENT statements
 *
 * Writes agentic/services/sapS4Schema.js. Re-run it when sap_s4.sync_state
 * reports schema_drift, then add the new columns in a migration (the --ddl
 * output shows their types and comments).
 */
require('dotenv').config({ path: require('path').join(__dirname, '..', '.env') });
const fs = require('fs');
const path = require('path');
const { S4Client, ENTITIES } = require('../agentic/services/sapS4Sync');

const arg = (name) => {
  const i = process.argv.indexOf(name);
  return i === -1 ? null : process.argv[i + 1];
};

/** 'GLAccount' → 'gl_account', 'YY1_FieldTicketNo_BDI' → 'field_ticket_no'. */
function columnName(field) {
  return field
    .replace(/^YY1_/, '')
    .replace(/_(BDI|PRD|BDH|SDI|SDH)$/, '')
    .replace(/FieldVu/g, 'Fieldvu')
    .replace(/([A-Z]+)([A-Z][a-z])/g, '$1_$2')
    .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
    .toLowerCase();
}

function pgType(type, attrs) {
  switch (type) {
    case 'Edm.DateTime':
      return /display-format="Date"/.test(attrs) ? 'date' : 'timestamptz';
    case 'Edm.DateTimeOffset':
      return 'timestamptz';
    case 'Edm.Decimal': {
      const p = attrs.match(/Precision="(\d+)"/);
      const s = attrs.match(/Scale="(\d+)"/);
      return p && s ? `numeric(${p[1]},${s[1]})` : 'numeric';
    }
    case 'Edm.Boolean':
      return 'boolean';
    case 'Edm.Byte':
    case 'Edm.Int16':
    case 'Edm.Int32':
      return 'integer';
    case 'Edm.Int64':
      return 'bigint';
    case 'Edm.Time':
      return 'time';
    default:
      return 'text';
  }
}

const xmlAttr = (attrs, name) => {
  const m = attrs.match(new RegExp(`${name}="([^"]*)"`));
  return m ? m[1].replace(/&amp;/g, '&').replace(/&quot;/g, '"').replace(/&apos;/g, "'") : null;
};

function parse(xml, view) {
  const entityType = `YY1_EXT_${view}_READType`;
  const block = (xml.match(new RegExp(`<EntityType Name="${entityType}"[\\s\\S]*?</EntityType>`)) || [])[0];
  if (!block) throw new Error(`${view}: EntityType ${entityType} not in $metadata`);
  const keys = [...block.match(/<Key>([\s\S]*?)<\/Key>/)[1].matchAll(/<PropertyRef Name="([^"]+)"/g)].map((m) => m[1]);
  const columns = [...block.matchAll(/<Property ([^>]*?)\/?>/g)].map((m) => {
    const attrs = m[1];
    const field = xmlAttr(attrs, 'Name');
    const type = pgType(xmlAttr(attrs, 'Type'), attrs);
    return {
      field,
      column: columnName(field),
      type: type.startsWith('numeric') ? 'numeric' : type,
      sqlType: type,
      key: keys.includes(field),
      label: xmlAttr(attrs, 'sap:quickinfo') || xmlAttr(attrs, 'sap:label') || field,
    };
  });
  const dupes = columns.map((c) => c.column).filter((c, i, all) => all.indexOf(c) !== i);
  if (dupes.length) throw new Error(`${view}: duplicate column names ${dupes.join(', ')}`);
  return { view, entityType, columns };
}

const sqlString = (s) => `'${String(s).replace(/'/g, "''")}'`;

function ddl(table, spec) {
  const lines = spec.columns.map((c) => `  ${c.column.padEnd(40)} ${c.sqlType.toUpperCase()}${c.key ? ' NOT NULL' : ''},`);
  const keys = spec.columns.filter((c) => c.key).map((c) => c.column);
  return [
    `CREATE TABLE IF NOT EXISTS sap_s4.${table} (`,
    ...lines,
    `  ${'synced_at'.padEnd(40)} TIMESTAMPTZ NOT NULL DEFAULT NOW(),`,
    `  PRIMARY KEY (${keys.join(', ')})`,
    ');',
    ...spec.columns.map((c) => `COMMENT ON COLUMN sap_s4.${table}.${c.column} IS ${sqlString(`${c.label} (SAP ${c.field})`)};`),
    '',
  ].join('\n');
}

(async () => {
  const from = arg('--from');
  const client = from ? null : new S4Client();
  const out = {};
  const sql = [];
  for (const e of ENTITIES) {
    const xml = from ? fs.readFileSync(path.join(from, `${e.view}.metadata.xml`), 'utf8') : await client.metadata(e.view);
    const spec = parse(xml, e.view);
    out[e.table] = {
      view: spec.view,
      entityType: spec.entityType,
      columns: spec.columns.map(({ sqlType, ...c }) => c),
    };
    sql.push(ddl(e.table, spec));
    console.log(`${e.table}: ${spec.columns.length} columns, key ${spec.columns.filter((c) => c.key).map((c) => c.column).join(' + ')}`);
  }

  const target = path.join(__dirname, '..', 'agentic', 'services', 'sapS4Schema.js');
  fs.writeFileSync(
    target,
    `/**\n * GENERATED by scripts/sap-s4-schema-gen.js from the S/4HANA views' $metadata. Do not edit by hand.\n * One entry per sap_s4 table: SAP field → column, Postgres type, key flag and SAP's field label.\n */\nmodule.exports = ${JSON.stringify(out, null, 2)};\n`
  );
  console.log(`wrote ${path.relative(process.cwd(), target)}`);
  const ddlFile = arg('--ddl');
  if (ddlFile) {
    fs.writeFileSync(ddlFile, sql.join('\n'));
    console.log(`wrote ${ddlFile}`);
  }
})().catch((err) => {
  console.error(err.message);
  process.exit(1);
});
